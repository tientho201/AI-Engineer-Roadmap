rearrange_shape = rearrange(x, "b (g c) h w -> b g c h w", g=3)
print("Rearrange shape:", rearrange_shape.shape)
reduce_shape = reduce(x, "b c h w -> b c", "mean")
print("Reduce shape:", reduce_shape.shape)
repeat_shape = repeat(x, "b c h w -> b c (h 2) w")
print("Repeat shape:", repeat_shape.shape)

